/* SSD1306 的 I2C 地址：
 * 7 位地址是 0x3C，HAL 发送时需要左移 1 位。
 */
#define OLED_ADDR 0x3C

/* 发送一条 OLED 命令。 */
static HAL_StatusTypeDef OLED_WriteCmd(uint8_t cmd)
{
  uint8_t buf[2] = {0x00, cmd};
  return HAL_I2C_Master_Transmit(&hi2c1, (uint16_t)(OLED_ADDR << 1), buf, 2, 100);
}

/* 发送一个 OLED 数据字节。 */
static HAL_StatusTypeDef OLED_WriteData(uint8_t data)
{
  uint8_t buf[2] = {0x40, data};
  return HAL_I2C_Master_Transmit(&hi2c1, (uint16_t)(OLED_ADDR << 1), buf, 2, 100);
}

/* 连续写入一小段显示数据：
 * 由于 I2C 单次发太多字节不够灵活，这里按最多 16 字节分块发送。
 */
static void OLED_WriteDataBlock(const uint8_t *data, uint16_t len)
{
  uint8_t buf[17];
  buf[0] = 0x40;
  while (len)
  {
    uint8_t chunk = (len > 16U) ? 16U : (uint8_t)len;
    memcpy(&buf[1], data, chunk);
    HAL_I2C_Master_Transmit(&hi2c1, (uint16_t)(OLED_ADDR << 1), buf, (uint16_t)(chunk + 1U), 100);
    data += chunk;
    len -= chunk;
  }
}

/* 设置 OLED 当前写入位置：
 * x    ：列地址
 * page ：页地址，每页对应垂直方向 8 个像素
 */
static void OLED_SetPos(uint8_t x, uint8_t page)
{
  OLED_WriteCmd(0xB0 + page);
  OLED_WriteCmd(0x00 + (x & 0x0F));
  OLED_WriteCmd(0x10 + ((x >> 4) & 0x0F));
}

