/* 根据字符返回对应的 ASCII 字模：
 * 这里只支持本工程实际要用到的字符。
 */
static const uint8_t* OLED_GetFont(char c)
{
  if (c == ' ') return font_space;
  if (c == ':') return font_colon;
  if (c >= '0' && c <= '9') return font_num[c - '0'];
  if (c >= 'a' && c <= 'z') c -= 32;
  if (c >= 'A' && c <= 'Z') return font_AZ[c - 'A'];
  return font_space;
}

/* SSD1306 初始化命令序列：
 * 配置寻址方式、扫描方向、对比度、多路复用比、电荷泵等。
 */
void OLED_Init(void)
{
  HAL_Delay(100);
  OLED_WriteCmd(0xAE);
  OLED_WriteCmd(0x20); OLED_WriteCmd(0x10);
  OLED_WriteCmd(0xB0);
  OLED_WriteCmd(0xC8);
  OLED_WriteCmd(0x00);
  OLED_WriteCmd(0x10);
  OLED_WriteCmd(0x40);
  OLED_WriteCmd(0x81); OLED_WriteCmd(0x7F);
  OLED_WriteCmd(0xA1);
  OLED_WriteCmd(0xA6);
  OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
  OLED_WriteCmd(0xA4);
  OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
  OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
  OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);
  OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
  OLED_WriteCmd(0xDB); OLED_WriteCmd(0x40);
  OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);
  OLED_WriteCmd(0xAF);
}

/* 整屏清空：
 * 逐页写入 0，适合上电初始化或重绘静态界面时使用。
 */
void OLED_Clear(void)
{
  uint8_t buf[129];
  buf[0] = 0x40;
  memset(&buf[1], 0x00, 128);

  for (uint8_t p = 0; p < 8; p++)
  {
    OLED_SetPos(0, p);
    HAL_I2C_Master_Transmit(&hi2c1, (uint16_t)(OLED_ADDR << 1), buf, sizeof(buf), 100);
  }
}

/* 局部清空显示区域：
 * 要求区域按 page 对齐，适合刷新动态数值区域，减少闪屏。
 */
void OLED_ClearArea(uint8_t x, uint8_t page, uint8_t width, uint8_t page_count)
{
  uint8_t zero[16] = {0};

  while (page_count--)
  {
    uint8_t remain = width;
    uint8_t xpos = x;
    OLED_SetPos(xpos, page);
    while (remain)
    {
      uint8_t chunk = (remain > sizeof(zero)) ? (uint8_t)sizeof(zero) : remain;
      OLED_WriteDataBlock(zero, chunk);
      xpos = (uint8_t)(xpos + chunk);
      remain = (uint8_t)(remain - chunk);
    }
    page++;
  }
}

/* 显示一个 16x16 的汉字字模：
 * 一个汉字占 2 页 * 16 列，共 32 字节。
 */
void OLED_ShowChinese(uint8_t x, uint8_t page, const uint8_t *glyph)
{
  OLED_SetPos(x, page);
  OLED_WriteDataBlock(glyph, 16);
  OLED_SetPos(x, (uint8_t)(page + 1U));
  OLED_WriteDataBlock(&glyph[16], 16);
}

/* 连续显示多个 16x16 汉字。 */
void OLED_ShowChineseString(uint8_t x, uint8_t page, const uint8_t *glyphs[], uint8_t count)
{
  for (uint8_t i = 0; i < count; i++)
  {
    OLED_ShowChinese((uint8_t)(x + i * 16U), page, glyphs[i]);
  }
}

/* 显示一个 6x8 ASCII 字符。 */
void OLED_ShowChar(uint8_t x, uint8_t page, char chr)
{
  const uint8_t *f = OLED_GetFont(chr);
  OLED_SetPos(x, page);
  for (uint8_t i = 0; i < 6; i++) OLED_WriteData(f[i]);
}

/* 显示以 '\\0' 结尾的 ASCII 字符串。 */
void OLED_ShowString(uint8_t x, uint8_t page, const char *str)
{
  while (*str && x <= 122)
  {
    OLED_ShowChar(x, page, *str++);
    x += 6;
  }
}

/* 以固定宽度显示十进制数字：
 * 宽度不足时左侧补空格，便于同一位置反复刷新数值。
 */
void OLED_ShowNumber(uint8_t x, uint8_t page, uint32_t num, uint8_t width)
{
  char buf[12];
  if (width >= sizeof(buf)) width = sizeof(buf) - 1;
  snprintf(buf, sizeof(buf), "%*lu", width, (unsigned long)num);
  OLED_ShowString(x, page, buf);
}
